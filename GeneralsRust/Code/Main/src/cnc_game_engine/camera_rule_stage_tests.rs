//! Actual detached map admission and SnapshotBuilder, with receiving rules distinct from active rules.
use super::*;
use crate::save_load::{GameDifficulty, SaveFileType};
#[test]
fn legacy_camera_restore_uses_saved_map_rules_not_active_or_application_maximum() {
    crate::game_logic::game_logic::pose_owner_tests::isolated_at(
        module_path!(),
        "legacy_camera_restore_uses_saved_map_rules_not_active_or_application_maximum",
        || {
            let temp = tempfile::tempdir().unwrap();
            let path = temp.path().join("SavedCamera.map");
            let mut map = game_engine::common::system::DataChunkOutput::new();
            map.open_data_chunk("GlobalLighting", 1);
            map.write_int(2);
            for _ in 0..4 {
                for _ in 0..2 {
                    for value in [0.1, 0.2, 0.3, 0.8, 0.8, 0.8, 0., 0., -1.] {
                        map.write_real(value);
                    }
                }
            }
            map.close_data_chunk();
            std::fs::write(&path, map.into_ckmp_bytes()).unwrap();
            std::fs::write(
                temp.path().join("Map.ini"),
                "GameData\n MinCameraHeight = 200\n MaxCameraHeight = 600\n KeyboardDefaultScrollSpeedFactor = 0.675\n DisableCameraMovements = Yes\n End\n",
            )
            .unwrap();
            std::fs::write(
                temp.path().join("Solo.ini"),
                "GameData\n DisableCameraMovements = No\n KeyboardDefaultScrollSpeedFactor = 0.375\n End\n",
            )
            .unwrap();
            let rules = crate::presentation_frame::camera::settings::CameraContentRules {
                min_camera_height: 100.,
                max_camera_height: 300.,
                ..Default::default()
            };
            let mut active = GameLogic::new();
            active.admit_camera_application_rules(rules).unwrap();
            active.admit_camera_application_movement(
                game_engine::common::ini::ini_game_data::CameraMovementRules {
                    disable_camera_movement: true,
                    ..Default::default()
                },
            );
            active
                .admit_camera_map_rules(
                    crate::presentation_frame::camera::settings::CameraContentRules {
                        max_camera_height: 900.,
                        ..rules
                    },
                )
                .unwrap();
            active.admit_camera_application_input(
                game_engine::common::ini::ini_game_data::CameraInputRules {
                    keyboard_default_scroll_factor: 0.25,
                    ..Default::default()
                },
            );
            active
                .apply_camera_input_overrides(&[
                    "GameData\n KeyboardDefaultScrollSpeedFactor = 0.9\nEnd\n".into(),
                ])
                .unwrap();
            let peer = GameLogic::new();
            let before = active.capture_camera_continuation().unwrap();
            let peer_before = peer.capture_camera_continuation().unwrap();
            let mut source = GameLogic::new();
            source.admit_camera_application_rules(rules).unwrap();
            crate::skirmish_config::lobby_definition_tests::admit_slot_definitions();
            let config = crate::skirmish_config::golden_skirmish_config(path.to_str().unwrap());
            crate::skirmish_config::apply_skirmish_config(&mut source, &config).unwrap();
            // Capture the roster generated by the SAME saved map that the
            // detached candidate will load; an un-loaded Skirmish is not a
            // valid complete roster for this map.
            assert!(source.load_map(path.to_str().unwrap()));
            let builder = crate::save_load::snapshot::SnapshotBuilder::new();
            let mut snapshot = builder.create_world_snapshot(&source).unwrap();
            let captured = GameLogic::decode_camera_continuation(
                &source.capture_camera_continuation().unwrap(),
            )
            .unwrap();
            let mut legacy = serde_json::to_value(captured).unwrap();
            legacy["script_default_camera_max_height"] = serde_json::json!(0.75);
            let legacy: crate::game_logic::LogicCameraContinuation =
                serde_json::from_value(legacy).unwrap();
            let logic = crate::save_load::camera_codec::CameraCodec::<{ 4 * 1024 * 1024 }>
                .serialize(&legacy)
                .unwrap();
            GameLogic::decode_camera_continuation(&logic).unwrap();
            let mut payload = Vec::new();
            payload.extend_from_slice(&(logic.len() as u32).to_le_bytes());
            payload.extend(logic);
            payload.extend_from_slice(&0u32.to_le_bytes());
            let mut framed = b"CAMC".to_vec();
            framed.extend_from_slice(&1u32.to_le_bytes());
            framed.extend_from_slice(&((payload.len() * 2) as u32).to_le_bytes());
            for value in payload {
                framed.extend(format!("{value:02x}").as_bytes());
            }
            let at = snapshot
                .lifecycle_tail
                .windows(4)
                .position(|word| word == b"CAMC")
                .unwrap();
            let len =
                u32::from_le_bytes(snapshot.lifecycle_tail[at + 8..at + 12].try_into().unwrap())
                    as usize;
            snapshot.lifecycle_tail.splice(at..at + 12 + len, framed);
            let info = SaveGameInfo {
                pristine_map_name: None,
                filename: "camera".into(),
                display_name: "camera".into(),
                description: "receiving rules".into(),
                map_name: path.to_str().unwrap().into(),
                campaign_side: None,
                mission_number: None,
                save_date: std::time::SystemTime::now(),
                game_version: env!("CARGO_PKG_VERSION").into(),
                play_time: std::time::Duration::ZERO,
                difficulty: GameDifficulty::Medium,
                save_type: SaveFileType::Normal,
            };
            for (map_text, solo_text, expected_disable) in [
                (
                    "GameData\n MinCameraHeight = 200\n MaxCameraHeight = 600\n KeyboardDefaultScrollSpeedFactor = 0.675\n DisableCameraMovements = Yes\n End\n",
                    "GameData\n DisableCameraMovements = No\n KeyboardDefaultScrollSpeedFactor = 0.375\n End\n",
                    false,
                ),
                (
                    "GameData\n MinCameraHeight = 200\n MaxCameraHeight = 600\n KeyboardDefaultScrollSpeedFactor = 0.675\n End\n",
                    "GameData\n MaxCameraHeight = 600\n KeyboardDefaultScrollSpeedFactor = 0.375\n End\n",
                    true,
                ),
            ] {
                std::fs::write(temp.path().join("Map.ini"), map_text).unwrap();
                std::fs::write(temp.path().join("Solo.ini"), solo_text).unwrap();
                let staged = CnCGameEngine::stage_decoded_saved_world_for_restore(
                &snapshot,
                info.clone(),
                None,
                None,
                        None, // no paired TerrainVisual in this direct staging fixture
                "camera",
                crate::game_logic::GameMode::Skirmish,
                &source.templates,
                &source.weapon_definition_base,
                &source.projectile_definitions,
                &source.ocl_application_definitions(),
                source.ai_definitions.baseline(),
                source.production_energy_baseline(),
                source.physics_rules_baseline(),
                active.session_view.camera.settings,
                active.session_view.camera.clip_policy,
                active.session_view.camera.shake_policy,
                active.session_view.camera.movement_policy,
                active.session_view.camera.input_policy,
                &active.world_services,
                |snapshot, candidate| {
                    assert_eq!(candidate.camera_input_rules().keyboard_default_scroll_factor,0.375);
                    assert_eq!(candidate.camera_movement_disabled(),expected_disable,
                        "saved map overrides or preserves receiving application policy in source order");
                    assert_eq!(
                        candidate
                            .session_view
                            .camera
                            .settings
                            .current()
                            .max_camera_height,
                        600.
                    );
                    assert_eq!(
                        candidate.session_view.camera.settings.bounds(),
                        (100., 900.)
                    );
                    builder
                        .restore_from_snapshot(snapshot, candidate)
                        .map_err(|e| e.to_string())?;
                    assert_eq!(candidate.camera_input_rules().keyboard_default_scroll_factor,0.375);
                    assert_eq!(candidate.camera_movement_disabled(),expected_disable,
                        "camera pose admission must not overwrite receiving map configuration");
                    assert_eq!(
                        candidate.session_view.camera.settings.bounds(),
                        (100., 450.)
                    );
                    Ok(())
                },
            )
            .unwrap();
                assert_eq!(
                    staged.logic.session_view.camera.settings.bounds(),
                    (100., 450.)
                );
                assert_eq!(
                    staged
                        .logic
                        .camera_input_rules()
                        .keyboard_default_scroll_factor,
                    0.375
                );
                drop(staged);
                assert_eq!(
                    active.camera_input_rules().keyboard_default_scroll_factor,
                    0.9
                );
                assert_eq!(
                    peer.camera_input_rules().keyboard_default_scroll_factor,
                    0.5
                );
                assert!(active.camera_movement_disabled());
                assert!(!peer.camera_movement_disabled());
                assert_eq!(before, active.capture_camera_continuation().unwrap());
                assert_eq!(peer_before, peer.capture_camera_continuation().unwrap());
            }
        },
    );
}
