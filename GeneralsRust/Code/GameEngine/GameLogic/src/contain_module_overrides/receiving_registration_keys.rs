#[cfg(test)]
mod tests {
    use super::*;
    use game_engine::common::name_key_generator::NameKeyNamespace;

    #[test]
    fn receiving_factory_allocates_original_registration_keys_before_authored_data() {
        let mut factory = ModuleFactory::new_receiving(NameKeyNamespace::new());
        assert_eq!(
            factory.receiving_name_keys_mut().unwrap().key_to_name(1),
            None,
            "metadata discovery must not manufacture source registration events"
        );
        super::super::register_native_module_overrides(&mut factory).unwrap();
        let keys = factory.receiving_name_keys_mut().unwrap();
        assert_eq!(keys.key_to_name(1).as_deref(), Some("0AutoHealBehavior"));
        let mut seen = std::collections::HashSet::new();
        let mut next_key = 1;
        for &(name, kind) in ORIGINAL_REGISTRATION {
            let decorated = format!("{}{}", kind as u8, name);
            if seen.insert(decorated.clone()) {
                assert_eq!(
                    keys.key_to_name(next_key).as_deref(),
                    Some(decorated.as_str())
                );
                next_key += 1;
            }
        }
        let after_registration = next_key;
        assert_eq!(keys.name_to_key("FirstAuthoredName"), after_registration);
        super::super::register_native_module_overrides(&mut factory).unwrap();
        assert_eq!(
            factory
                .receiving_name_keys_mut()
                .unwrap()
                .name_to_key("FirstAuthoredName"),
            after_registration
        );
    }
}
